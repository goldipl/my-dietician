export const kcalFromMacros = (protein: number, carbs: number, fat: number) =>
  Math.round(protein * 4 + carbs * 4 + fat * 9);

export const recipes: RecipeWithKcal[] = RECIPES.map((r) => ({ ...r, kcal: kcalFromMacros(r.protein, r.carbs, r.fat) }));

export function getRecipe(id: string): RecipeWithKcal | undefined {
  return recipes.find((r) => r.id === id);
}
